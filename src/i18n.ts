export type Language = keyof typeof translations
export type TranslationKey = keyof typeof translations.vi
export type Messages = Omit<(typeof translations)[Language], 'products'>

type ProductTranslation = {
  name: string
  description: string
  tags?: readonly string[]
  sizes: Readonly<Record<string, string>>
  ingredients: readonly string[]
  preparationTime: string
  serving: string
  note: string
}

export const productTranslations: Record<
  Exclude<Language, 'vi'>,
  Record<string, ProductTranslation>
> = {
  en: translations.en.products,
  ja: translations.ja.products,
}

const numberLocales: Record<Language, string> = {
  vi: 'vi-VN',
  en: 'en-US',
  ja: 'ja-JP',
}

export function formatPrice(price: number, language: Language) {
  return new Intl.NumberFormat(numberLocales[language], {
    style: 'currency',
    currency: 'VND',
    maximumFractionDigits: 0,
  }).format(price)
}

export function formatMessage(
  message: string,
  values: Record<string, string | number>,
) {
  return message.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ''))
}
